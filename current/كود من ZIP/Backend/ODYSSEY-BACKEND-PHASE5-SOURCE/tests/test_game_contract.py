"""odyssey.game.v1 contract freeze: normalised OpenAPI snapshot, recorded Unreal handoff
examples (regenerated byte-identically and validated against the real models) and the API v1
freeze staying untouched by the game sub-application."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.tools import game_contract
from app.tools.openapi_snapshot import FIXTURE as V1_FIXTURE
from app.tools.openapi_snapshot import current_schema as v1_schema
from app.tools.openapi_snapshot import differences

EXAMPLES = game_contract.EXAMPLES


def _examples() -> dict[str, Any]:
    return {
        p.stem: json.loads(p.read_text(encoding="utf-8"))
        for p in sorted(EXAMPLES.glob("*.json"))
        if p.stem != "index"
    }


def test_game_contract_is_frozen_and_reproducible() -> None:
    """Regenerating the OpenAPI document and every example yields the committed files."""
    assert game_contract.main(["--check"]) == 0


def test_examples_validate_against_the_real_models() -> None:
    examples = _examples()
    assert set(examples) == set(game_contract.MODELS)
    assert game_contract.validate_examples(examples) == []
    index = json.loads((EXAMPLES / "index.json").read_text(encoding="utf-8"))
    assert set(index["examples"]) == set(examples)


def test_required_handoff_examples_exist() -> None:
    """Section 57's list."""
    required = {
        "bootstrap",
        "snapshot_incident",
        "command_request",
        "command_response",
        "error_stale_state",
        "event_inventory_changed",
        "event_incident_started",
        "event_mission_updated",
        "event_certification_granted",
        "future_lens_response",
        "black_box_response",
        "restore_response",
        "ws_resync_required",
    }
    assert required <= set(_examples())
    ex = _examples()
    assert ex["error_stale_state"]["error"]["code"] == "STALE_STATE"
    assert ex["event_incident_started"]["type"] == "incident.started"
    assert ex["event_certification_granted"]["type"] == "certification.granted"
    assert ex["event_inventory_changed"]["type"] in {"cargo.changed", "inventory.changed"}
    assert ex["ws_resync_required"]["type"] == "RESYNC_REQUIRED"
    assert ex["error_mars_locked"]["error"]["details"]["lock_code"] == "MARS_MISSION_LOCKED"


def test_examples_contain_no_internal_ids_or_seeds() -> None:
    text = json.dumps(_examples())
    # simulation session/timeline/decision ids are drawn from the d0d00000-… counter during
    # the recording run: none may appear in a game payload
    assert "d0d00000" not in text
    assert str(game_contract.SESSION_SEED) not in text
    assert "token_hash" not in text and '"seed"' not in text


def test_game_openapi_document_shape() -> None:
    schema = json.loads(game_contract.OPENAPI.read_text(encoding="utf-8"))
    assert schema["info"]["version"] == "odyssey.game.v1"
    assert schema["info"]["title"] == "ODYSSEY Game API"
    paths = schema["paths"]
    assert "/sessions/{session_id}/commands" in paths
    for path, ops in paths.items():
        for method, op in ops.items():
            codes = set(op["responses"])
            assert {"403", "404", "409", "422"} <= codes, f"{method} {path}"
    props: set[str] = set()
    for comp in schema["components"]["schemas"].values():
        props |= set(comp.get("properties", {}))
    # no per-frame / spatial data in the protocol (section 9)
    for forbidden in ("x", "y", "z", "position", "rotation", "velocity", "transform", "yaw"):
        assert forbidden not in props


def test_api_v1_snapshot_is_unchanged_by_the_game_mount() -> None:
    old = json.loads(Path(V1_FIXTURE).read_text(encoding="utf-8"))
    assert differences(old, v1_schema()) == []
    assert not any(p.startswith("/api/game") for p in v1_schema()["paths"])
