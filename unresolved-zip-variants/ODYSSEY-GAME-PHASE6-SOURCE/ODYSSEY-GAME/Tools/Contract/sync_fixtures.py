#!/usr/bin/env python3
"""Vendor the real odyssey.game.v1 contract artifacts from the backend repository.

The Unreal client is tested against the backend's *recorded* examples and frozen OpenAPI
document (backend: tests/fixtures/game/, generated by `python -m app.tools.game_contract`).
They are copied verbatim into Tests/Fixtures/odyssey.game.v1/ together with PROVENANCE.json
(backend commit + sha256 of every file), so a contract change on either side is visible.

    python3 Tools/Contract/sync_fixtures.py --backend ../odyssey --write
    python3 Tools/Contract/sync_fixtures.py --backend ../odyssey --check   # CI / before a commit
    python3 Tools/Contract/sync_fixtures.py --check                         # integrity only

Never edit the vendored files by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "Tests" / "Fixtures" / "odyssey.game.v1"
PROVENANCE = DEST / "PROVENANCE.json"
SOURCE_REL = Path("tests") / "fixtures" / "game"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def backend_commit(backend: Path) -> str:
    out = subprocess.run(
        ["git", "-C", str(backend), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    )
    return out.stdout.strip()


def source_files(backend: Path) -> list[Path]:
    src = backend / SOURCE_REL
    files = sorted(p for p in src.rglob("*.json") if p.is_file())
    if not files:
        raise SystemExit(f"no fixtures under {src}")
    return files


def write(backend: Path) -> int:
    src = backend / SOURCE_REL
    if DEST.exists():
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    files = {}
    for f in source_files(backend):
        rel = f.relative_to(src)
        (DEST / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(f, DEST / rel)
        files[str(rel)] = sha256(f)
    PROVENANCE.write_text(
        json.dumps(
            {
                "protocol": "odyssey.game.v1",
                "backend_commit": backend_commit(backend),
                "backend_path": str(SOURCE_REL),
                "generated_by": "python -m app.tools.game_contract --write (backend)",
                "files": files,
            },
            indent=1,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"vendored {len(files)} files from backend {backend_commit(backend)[:12]}")
    return 0


def check(backend: Path | None) -> int:
    if not PROVENANCE.exists():
        print("missing PROVENANCE.json; run --write")
        return 1
    prov = json.loads(PROVENANCE.read_text(encoding="utf-8"))
    problems = []
    for rel, digest in prov["files"].items():
        p = DEST / rel
        if not p.exists():
            problems.append(f"missing {rel}")
        elif sha256(p) != digest:
            problems.append(f"modified {rel}")
    extra = {str(p.relative_to(DEST)) for p in DEST.rglob("*.json")} - set(prov["files"]) - {"PROVENANCE.json"}
    problems += [f"unexpected {e}" for e in sorted(extra)]
    if backend is not None:
        src = backend / SOURCE_REL
        current = {str(f.relative_to(src)): sha256(f) for f in source_files(backend)}
        if current != prov["files"]:
            changed = sorted(set(current.items()) ^ set(prov["files"].items()))
            problems.append(f"backend fixtures differ from the vendored copy ({len(changed)} entries)")
        commit = backend_commit(backend)
        if commit != prov["backend_commit"]:
            print(f"note: backend HEAD {commit[:12]} != vendored {prov['backend_commit'][:12]}")
    if problems:
        print("\n".join(problems))
        return 1
    print(f"fixtures intact ({len(prov['files'])} files, backend {prov['backend_commit'][:12]})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--backend", type=Path)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.write:
        if args.backend is None:
            ap.error("--write needs --backend")
        return write(args.backend.resolve())
    return check(args.backend.resolve() if args.backend else None)


if __name__ == "__main__":
    sys.exit(main())
